    def moderate_player_chat(self, text: str) -> Dict[str, Any]:
        """Uses Meta Llama Guard 3 to moderate player names and multiplayer messages."""
        res = self.guard_shield.audit_prompt(text)
        return {
            "original_text": text,
            "is_safe": res.is_safe,
            "risk_level": res.risk_level,
            "sanitized_text": res.sanitized_input,
            "guard_score": res.prompt_guard_score
        }

    def export_game_bundle(self, output_dir: str = "dist_game_export") -> Dict[str, str]:
        """
        Exports ready-to-publish packages for Steam, Meta Horizon Worlds, and Web.
        """
        os.makedirs(output_dir, exist_ok=True)
        
        # 1. Meta Horizon Worlds Scene Graph JSON
        horizon_manifest = {
            "title": "MetaHorizon Odyssey",
            "team_id": self.team_id,
            "project_id": self.project_id,
            "target_platform": "Meta Horizon Worlds & Meta Quest",
            "tiers": LEVELING_TIERS,
            "components": [
                {"name": "PlayerGuardian", "type": "ActorController", "tier": 1},
                {"name": "ProceduralGridGenerator", "type": "EnvironmentSpawner"},
                {"name": "MetaAIGameForge", "type": "MuseCodeScriptHost"}
            ]
        }
        horizon_path = os.path.join(output_dir, "meta_horizon_world_manifest.json")
        with open(horizon_path, "w", encoding="utf-8") as f:
            json.dump(horizon_manifest, f, indent=2)

